# Installs or updates NeoShard on a Windows host without Docker (run elevated).
#   install.ps1 -Package C:\NeoShard\incoming\neoshard-pkg.zip -Domain chat.example.ru -PublicIp 203.0.113.7
# The package (built by deploy/windows/pack.sh) holds bin\, web\, pgsql\, livekit\, caddy\ and scripts\.
# Components: PostgreSQL as a Windows service; the server, LiveKit and Caddy as boot-time
# scheduled tasks under SYSTEM (run.ps1 restarts them). Nothing needs a user to be logged in.
# Secrets are generated here on first install and never leave this machine.
param(
    [Parameter(Mandatory = $true)][string]$Package,
    [Parameter(Mandatory = $true)][string]$Domain,
    [Parameter(Mandatory = $true)][string]$PublicIp,
    [string]$Root = 'C:\NeoShard'
)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$Tasks = 'server', 'livekit', 'caddy'

function Rand([int]$bytes) {
    $b = New-Object byte[] $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return $b
}
function Hex([int]$bytes) { return (-join ((Rand $bytes) | ForEach-Object { $_.ToString('x2') })) }

foreach ($d in 'config', 'data\files', 'logs', 'incoming') { New-Item -ItemType Directory -Force "$Root\$d" | Out-Null }

# --- stop what is running, then unpack the new files
foreach ($t in $Tasks) { Stop-ScheduledTask -TaskName "NeoShard-$t" -ErrorAction SilentlyContinue }
Get-Process neoshard-server, livekit-server, caddy -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -like "$Root\*" } | Stop-Process -Force
Start-Sleep 2
$tmp = "$Root\incoming\unpacked"
if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
Expand-Archive -Path $Package -DestinationPath $tmp
foreach ($d in 'bin', 'web', 'site', 'livekit', 'caddy', 'scripts') {
    if (-not (Test-Path "$tmp\$d")) { continue }
    if ($d -eq 'web' -and (Test-Path "$Root\web")) { Remove-Item -Recurse -Force "$Root\web" }
    New-Item -ItemType Directory -Force "$Root\$d" | Out-Null
    # site.json (donation links) may be edited on the server: keep that copy.
    $keep = @()
    if ($d -eq 'site' -and (Test-Path "$Root\site\site.json")) { $keep = @('site.json') }
    Get-ChildItem "$tmp\$d" | Where-Object { $keep -notcontains $_.Name } |
        Copy-Item -Recurse -Force -Destination "$Root\$d"
}
New-Item -ItemType Directory -Force "$Root\downloads" | Out-Null
$pgService = Get-Service NeoShardPostgres -ErrorAction SilentlyContinue
if (-not $pgService) {
    # PostgreSQL binaries are only replaced on a fresh install (the service keeps them open).
    if (Test-Path "$Root\pgsql") { Remove-Item -Recurse -Force "$Root\pgsql" }
    Copy-Item -Recurse "$tmp\pgsql" "$Root\pgsql"
}

# --- settings and secrets
@{ domain = $Domain; public_ip = $PublicIp } | ConvertTo-Json | Set-Content -Encoding ASCII "$Root\config\settings.json"
$secFile = "$Root\config\secrets.json"
if (-not (Test-Path $secFile)) {
    @{
        secret_key     = [Convert]::ToBase64String((Rand 32))
        db_password    = Hex 24
        pg_password    = Hex 24
        livekit_key    = 'NS' + (Hex 8)
        livekit_secret = Hex 32
    } | ConvertTo-Json | Set-Content -Encoding ASCII $secFile
}
# Only administrators and SYSTEM may read the config (secrets).
icacls "$Root\config" /inheritance:r /grant '*S-1-5-32-544:(OI)(CI)F' /grant '*S-1-5-18:(OI)(CI)F' | Out-Null
$sec = Get-Content $secFile -Raw | ConvertFrom-Json

@"
# Generated by install.ps1
$Domain {
	encode zstd gzip
	# handle blocks: try_files would otherwise rewrite API paths to index.html first.
	@backend path /api/* /gateway* /.well-known/neoshard /federation/* /healthz /files/*
	handle @backend {
		reverse_proxy 127.0.0.1:8080 {
			header_up X-Real-IP {remote_host}
		}
	}
	# Releases published by deploy/windows/publish-downloads.sh
	handle /downloads/* {
		root * $($Root -replace '\\','/')
		header Cache-Control "no-cache"
		file_server
	}
	# Web client under /app/ (built with NEOSHARD_WEB_BASE=app)
	redir /app /app/ 308
	# Invite links open the web client with the join dialog
	@invite path_regexp invite ^/invite/([A-Za-z0-9_-]+)/?$
	redir @invite /app/?invite={re.invite.1} 302
	handle_path /app/* {
		root * $($Root -replace '\\','/')/web
		@wasm path *.wasm
		header @wasm Content-Type application/wasm
		header /assets/* Cache-Control "public, max-age=31536000, immutable"
		try_files {path} /index.html
		file_server
	}
	# Landing site
	handle {
		root * $($Root -replace '\\','/')/site
		try_files {path} /index.html
		file_server
	}
}

# LiveKit signalling with TLS (clients connect to wss://$($Domain):7880)
$($Domain):7880 {
	reverse_proxy 127.0.0.1:7890
}
"@ | Set-Content -Encoding ASCII "$Root\config\Caddyfile"

@"
# Generated by install.ps1
port: 7890
rtc:
  tcp_port: 7881
  udp_port: 7882
  port_range_start: 50000
  port_range_end: 50100
  node_ip: $PublicIp
  use_external_ip: false
keys:
  $($sec.livekit_key): $($sec.livekit_secret)
logging:
  level: info
"@ | Set-Content -Encoding ASCII "$Root\config\livekit.yaml"

# --- PostgreSQL (listens on localhost only)
$pg = "$Root\pgsql\bin"
$data = "$Root\pgdata"
if (-not (Test-Path "$data\PG_VERSION")) {
    # initdb drops admin rights, so the password file cannot sit in the locked config folder.
    $pw = "$Root\incoming\pgpw.txt"
    [IO.File]::WriteAllText($pw, $sec.pg_password)
    & "$pg\initdb.exe" -D $data -U postgres -A scram-sha-256 -E UTF8 --locale=C --pwfile=$pw | Out-Null
    Remove-Item $pw
    if ($LASTEXITCODE -ne 0) { throw 'initdb failed' }
}
icacls $data /grant '*S-1-5-20:(OI)(CI)M' | Out-Null
if (-not $pgService) {
    & "$pg\pg_ctl.exe" register -N NeoShardPostgres -U 'NT AUTHORITY\NetworkService' -D $data -S auto | Out-Null
}
Start-Service NeoShardPostgres
$env:PGPASSWORD = $sec.pg_password
for ($i = 0; $i -lt 30; $i++) {
    & "$pg\pg_isready.exe" -h 127.0.0.1 -p 5432 -q
    if ($LASTEXITCODE -eq 0) { break }
    Start-Sleep 1
}
$exists = & "$pg\psql.exe" -h 127.0.0.1 -U postgres -d postgres -tAc "SELECT 1 FROM pg_roles WHERE rolname='neoshard'"
if ($exists -ne '1') {
    & "$pg\psql.exe" -h 127.0.0.1 -U postgres -d postgres -q -c "CREATE ROLE neoshard LOGIN PASSWORD '$($sec.db_password)'" -c 'CREATE DATABASE neoshard OWNER neoshard'
    if ($LASTEXITCODE -ne 0) { throw 'creating the database failed' }
}
Remove-Item Env:\PGPASSWORD

# --- boot-time tasks
foreach ($t in $Tasks) {
    $action = New-ScheduledTaskAction -Execute 'powershell.exe' `
        -Argument "-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Root\scripts\run.ps1`" -Name $t"
    $settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 `
        -RestartInterval (New-TimeSpan -Minutes 1) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable
    Register-ScheduledTask -TaskName "NeoShard-$t" -Action $action -Trigger (New-ScheduledTaskTrigger -AtStartup) `
        -Principal (New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest) `
        -Settings $settings -Force | Out-Null
    Start-ScheduledTask -TaskName "NeoShard-$t"
}
Remove-Item -Recurse -Force $tmp
"installed: https://$Domain"
